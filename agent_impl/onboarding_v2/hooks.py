def resolve_multi_hook(qid: str, selected: list[str]) -> dict | None:
    """根据多选结果解析出钩子。

    参数：
    - qid：题号（只有 A3/A4 需要这个函数，其他题请直接读 `HOOKS[qid]`)
    - selected：用户选中的选项 id 列表，例如 `["A", "C"]`

    返回：`{"text": str, "image": str | None}` 或 None。

    匹配规则：
    - 只选 1 项 → 按 `priority` 顺序，取第一个命中的单选钩子
    - 选 2+ 项 → 遍历 `multi_rules`，命中第一条即返回；fallback 保底

    ⚠️ 本函数只负责文案解析，不做前端交互。前端如果要做纯 JS 版，
       请参考同目录 `question_bank.frontend.json` 中的相同规则。
    """

    q = HOOKS.get(qid)
    if not q:
        return None

    sel = set(selected)

    # 单选情况：按优先级找到最高权重
    if len(sel) <= 1 and "priority" in q:
        for pid in q["priority"]:
            if pid in sel:
                return q["single"].get(pid)
        return None

    # 多选情况：遍历规则
    for rule in q.get("multi_rules", []):
        match = rule["match"]
        if match.get("fallback"):
            return rule["hook"]
        # required：必须全部在选中列表里
        if "required" in match:
            req = set(match["required"])
            if not req.issubset(sel):
                continue
            # 如果还有 any_of，需要至少命中一个
            if "any_of" in match:
                if not set(match["any_of"]) & (sel - req):
                    continue
            return rule["hook"]
        # any_of_sets：任一组合被完全覆盖即可
        if "any_of_sets" in match:
            for combo in match["any_of_sets"]:
                if set(combo).issubset(sel):
                    return rule["hook"]

    return None
